namespace Factory.Core

open System
open System.Text
open System.Text.Json

/// One recorded response: status and its JSON or text body.
type ReplayResponse = { Status: int; MimeType: string; Body: string }

/// The responses recorded for one method and path, in recorded order. `Path` has numeric and uuid segments as `:id`, so a page that asks
/// for another record than the one recorded is still served.
type ReplayGroup = { Method: string; Path: string; Responses: ReplayResponse list }

/// F9: a HAR as the handlers a page test replays (docs/ui-contract-verify.md). Pure: a HAR in, handler data out. Only the fields a
/// minimal HAR has are read (`request.method`, `request.url`, `response.status`, `response.content.mimeType` and `.text`).
[<RequireQualifiedAccess>]
module HarReplay =
    let private str (e: JsonElement) (name: string) =
        match e.TryGetProperty name with
        | true, v when v.ValueKind = JsonValueKind.String -> Some(v.GetString())
        | _ -> None

    let private keeps (mime: string) =
        let m = mime.ToLowerInvariant()
        m.Contains "json" || m.StartsWith "text/"

    /// Groups in first-recorded order, then the ones with fewer `:id` segments first, so `/x/summary` is tried before `/x/:id`.
    /// Error: the HAR is not JSON or has no entries a page could be served from.
    let groups (harJson: string) : Result<ReplayGroup list, string> =
        try
            use d = JsonDocument.Parse harJson
            let entries =
                match d.RootElement.TryGetProperty "log" with
                | true, log ->
                    (match log.TryGetProperty "entries" with
                     | true, es when es.ValueKind = JsonValueKind.Array -> [ for e in es.EnumerateArray() -> e.Clone() ]
                     | _ -> [])
                | _ -> []
            let rows =
                [ for e in entries do
                      match e.TryGetProperty "request", e.TryGetProperty "response" with
                      | (true, rq), (true, rs) ->
                          let content = match rs.TryGetProperty "content" with | true, c -> Some c | _ -> None
                          let mime = content |> Option.bind (fun c -> str c "mimeType") |> Option.defaultValue ""
                          let text = content |> Option.bind (fun c -> str c "text")
                          let status = match rs.TryGetProperty "status" with | true, s when s.ValueKind = JsonValueKind.Number -> s.GetInt32() | _ -> 200
                          match str rq "method", str rq "url", text with
                          | Some m, Some u, Some body when keeps mime && status > 0 ->
                              let path = match Uri.TryCreate(u, UriKind.Absolute) with | true, uri -> uri.AbsolutePath | _ -> u.Split('?').[0]
                              yield m.ToUpperInvariant(), RequestParity.template path, { Status = status; MimeType = mime; Body = body }
                          | _ -> ()
                      | _ -> () ]
            if rows.IsEmpty then Error "the HAR has no JSON or text response a page could be served from"
            else
                let order = rows |> List.map (fun (m, p, _) -> m, p) |> List.distinct
                order
                |> List.map (fun (m, p) -> { Method = m; Path = p; Responses = rows |> List.filter (fun (m2, p2, _) -> m2 = m && p2 = p) |> List.map (fun (_, _, r) -> r) })
                |> List.sortBy (fun g -> g.Path.Split('/') |> Array.filter (fun s -> s = ":id") |> Array.length)
                |> Ok
        with :? JsonException -> Error "the HAR is not valid JSON"

    /// What the generated test imports: `[{method, path, responses: [{status, mimeType, body}]}]`.
    let toJson (gs: ReplayGroup list) : string =
        let sb = StringBuilder("[")
        gs |> List.iteri (fun i g ->
            if i > 0 then sb.Append(',') |> ignore
            sb.Append("{\"method\":").Append(JsonSerializer.Serialize g.Method).Append(",\"path\":").Append(JsonSerializer.Serialize g.Path).Append(",\"responses\":[") |> ignore
            g.Responses |> List.iteri (fun j r ->
                if j > 0 then sb.Append(',') |> ignore
                sb.Append("{\"status\":").Append(r.Status).Append(",\"mimeType\":").Append(JsonSerializer.Serialize r.MimeType).Append(",\"body\":").Append(JsonSerializer.Serialize r.Body).Append('}') |> ignore)
            sb.Append("]}") |> ignore)
        sb.Append(']').ToString()

    let private template = """import React from "react";
import { describe, test, expect } from "vitest";
import { page } from "vitest/browser";
import { render } from "vitest-browser-react";
import groups from "../replay/@SCREEN@.json";
import { @COMPONENT@ as Page } from "../../@FILE@";
import { replayHandlers, useWorker } from "../preview/vitest-ui";

// Generated by `factory-s2 replay`: the page rendered against a recorded HAR, in a scratch copy. It fails when the page asks for a
// request the HAR does not hold. The message names endpoints only.
describe("@SCREEN@ replay", () => {
  const worker = useWorker();
  const unserved: string[] = [];
  worker.events.on("request:unhandled", ({ request }: any) => { unserved.push(`${request.method} ${new URL(request.url).pathname}`); });

  test("served from the HAR", async () => {
    worker.use(...replayHandlers(groups as any));
    await render(<div data-testid="ui-root"><Page /></div>);
    await expect.element(page.getByTestId("ui-root")).toBeInTheDocument();
    await new Promise((r) => setTimeout(r, 750)); // the page's own fetches settle
    expect(unserved.length, `replay_unserved: ${[...new Set(unserved)].join(", ")}`).toBe(0);
  });
});
"""

    /// The marker the generated test's failure carries; the runner looks for it to tell "the HAR lacks a request" from "could not run".
    [<Literal>]
    let UnservedMarker = "replay_unserved:"

    let testText (screen: string) (component': string) (file: string) : string =
        let noExt = System.Text.RegularExpressions.Regex.Replace(file.Replace('\\', '/'), @"\.[A-Za-z0-9]+$", "")
        template.Replace("@SCREEN@", screen).Replace("@COMPONENT@", component').Replace("@FILE@", noExt)
